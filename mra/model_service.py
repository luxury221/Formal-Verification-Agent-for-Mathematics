"""Provider-neutral DTOs. A transport must enforce its own request deadline."""

from __future__ import annotations

from dataclasses import asdict, dataclass
import math
from typing import Protocol

from .domain import digest


def text_field(value: object, name: str, limit: int = 16000) -> str:
    if not isinstance(value, str) or not value.strip() or len(value) > limit:
        raise ValueError(f"{name} must be nonempty text of at most {limit} characters")
    return value


def integer_field(value: object, name: str, minimum: int, maximum: int) -> int:
    if type(value) is not int or not minimum <= value <= maximum:
        raise ValueError(f"{name} must be an integer in [{minimum}, {maximum}]")
    return value


@dataclass(frozen=True)
class ModelIdentity:
    provider: str
    model: str
    revision: str
    kind: str

    def __post_init__(self) -> None:
        for name in ("provider", "model", "revision"):
            text_field(getattr(self, name), name, 256)
        if self.revision.casefold() in ("latest", "main", "master", "head"):
            raise ValueError("Model revision must identify a resolved version, not a mutable alias")
        if self.kind not in ("model", "fixture"):
            raise ValueError("Producer kind must distinguish model from fixture")


@dataclass(frozen=True)
class ModelBudget:
    timeout_seconds: float = 30.0
    max_input_chars: int = 16000
    max_output_tokens: int = 2048
    max_output_bytes: int = 65536

    def __post_init__(self) -> None:
        if (
            type(self.timeout_seconds) not in (float, int)
            or not math.isfinite(self.timeout_seconds)
            or not 0 < self.timeout_seconds <= 120
        ):
            raise ValueError("Model timeout must be finite and in (0, 120] seconds")
        integer_field(self.max_input_chars, "max_input_chars", 1, 100000)
        integer_field(self.max_output_tokens, "max_output_tokens", 1, 32768)
        integer_field(self.max_output_bytes, "max_output_bytes", 1, 1048576)


@dataclass(frozen=True)
class ModelRequest:
    id: str
    task: str
    input_json: str
    budget: ModelBudget
    output_schema: str = "formalizer-output-v1"

    def __post_init__(self) -> None:
        text_field(self.id, "request id", 128)
        text_field(self.input_json, "model input", 1048576)
        schemas = {
            "formalize_claim": "formalizer-output-v1",
            "formalize_step": "formalizer-output-v1",
            "nat_formalize": "nat-formalizer-output-v1",
            "nat_prove": "nat-proof-output-v1",
            "math_research_plan": "math-research-plan-v1",
            "math_research_step": "math-research-step-v1",
        }
        if schemas.get(self.task) != self.output_schema:
            raise ValueError("Unsupported model task or output schema")
        if not isinstance(self.budget, ModelBudget):
            raise ValueError("Model request needs a validated budget")

    @property
    def fingerprint(self) -> str:
        return digest(asdict(self))


@dataclass(frozen=True)
class TokenUsage:
    input_tokens: int
    output_tokens: int

    def __post_init__(self) -> None:
        integer_field(self.input_tokens, "input_tokens", 0, 10000000)
        integer_field(self.output_tokens, "output_tokens", 0, 10000000)


@dataclass(frozen=True)
class ModelResponse:
    request_fingerprint: str
    identity: ModelIdentity
    output_json: str
    usage: TokenUsage


class ModelService(Protocol):
    """Identity/usage come from the adapter, never from text generated by a model.

    Implementations must bound their network/process wait using request.budget,
    and raise TimeoutError or OSError on transport failure, ValueError for an
    invalid provider response. No implicit retry.
    """

    def generate(self, request: ModelRequest) -> ModelResponse: ...
